#!/usr/bin/env python3
"""Structural checks for the static site (no build step, so this is the test suite).
Run: python3 tests/check_site.py
"""
import hashlib
import json
import re
import sys
import xml.dom.minidom as minidom
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
failures = []


def check(name, condition):
    print(f"[{'PASS' if condition else 'FAIL'}] {name}")
    if not condition:
        failures.append(name)


html = (ROOT / "index.html").read_text(encoding="utf-8")

# JSON-LD blocks must be valid JSON (the Organization/SoftwareApplication @graph,
# BreadcrumbList, and FAQPage schemas that AEO/rich-results depend on).
ld_blocks = re.findall(r'<script type="application/ld\+json">(.*?)</script>', html, re.S)
check("index.html has JSON-LD blocks", len(ld_blocks) > 0)
for i, block in enumerate(ld_blocks):
    try:
        json.loads(block)
        ok = True
    except json.JSONDecodeError as e:
        ok = False
        print(f"    JSON-LD block {i}: {e}")
    check(f"JSON-LD block {i} is valid JSON", ok)

# FAQPage JSON-LD must mirror the visible #faq items (AEO: Google requires marked-up
# Q&As to be visible on the page).
faq_ld = [json.loads(b) for b in ld_blocks if '"FAQPage"' in b]
visible_q = re.findall(r'<summary class="faq-question"[^>]*>(.*?)</summary>', html, re.S)
ld_q = [q["name"] for q in faq_ld[0]["mainEntity"]] if faq_ld else []
check("FAQPage JSON-LD questions match visible FAQ questions", ld_q == [q.strip() for q in visible_q])

# Product naming: SetTime's official product page is its own subdomain.
SETTIME_URL = "https://settime.kairosaitech.com/"
graph = next((json.loads(b) for b in ld_blocks if '"@graph"' in b), {"@graph": []})
software = [n for n in graph["@graph"] if n.get("@type") == "SoftwareApplication"]
check("JSON-LD has a SoftwareApplication named SetTime at the product URL",
      any(n.get("name") == "SetTime" and n.get("url") == SETTIME_URL for n in software))
check("product CTA links to the SetTime product page", f'href="{SETTIME_URL}"' in html)

# sitemap.xml must be well-formed XML.
try:
    minidom.parse(str(ROOT / "sitemap.xml"))
    ok = True
except Exception as e:
    ok = False
    print(f"    sitemap.xml: {e}")
check("sitemap.xml is well-formed XML", ok)

# robots.txt sanity.
robots = (ROOT / "robots.txt").read_text(encoding="utf-8")
check("robots.txt declares a Sitemap", "Sitemap:" in robots)
check("robots.txt has a User-agent rule", "User-agent:" in robots)

# Every in-page #anchor href must resolve to a real element id (catches a new
# section being linked before its id exists, or an id being renamed/removed).
ids = set(re.findall(r'\bid="([^"]+)"', html))
anchors = {a for a in re.findall(r'href="#([^"]+)"', html) if a}
missing = anchors - ids
check(f"all #anchor links resolve to an existing id (missing: {sorted(missing) or 'none'})", not missing)

# Agent-discovery files that other files (llms.txt, index.md, <head> link rels)
# point to must actually exist.
for rel in [
    "llms.txt",
    "index.md",
    "robots.txt",
    "sitemap.xml",
    ".well-known/api-catalog",
    ".well-known/mcp/server-card.json",
    ".well-known/agent-skills/index.json",
]:
    check(f"{rel} exists", (ROOT / rel).is_file())

# Agent skills index sha256 digests must match the SKILL.md files they describe
# (agents that verify the digest reject a skill whose file changed without it).
skills_index = json.loads((ROOT / ".well-known/agent-skills/index.json").read_text(encoding="utf-8"))
for skill in skills_index.get("skills", []):
    rel = skill["url"].split("kairosaitech.com/", 1)[1]
    path = ROOT / rel
    digest = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None
    check(f"agent skill {skill.get('name', rel)} sha256 matches {rel}", digest == skill.get("sha256"))

# script.js sanity (CI also runs `node --check` separately for real syntax validation).
js = (ROOT / "script.js").read_text(encoding="utf-8")
check("script.js braces are balanced", js.count("{") == js.count("}"))

# Per-language pages (generated by scripts/build-locales.mjs).
sitemap_xml = (ROOT / "sitemap.xml").read_text(encoding="utf-8")
check("sitemap.xml has no ?lang= URLs", "?lang=" not in sitemap_xml)
for code, folder in [("zh-Hant", "zh-tw"), ("ja", "ja"), ("es", "es"), ("it", "it"), ("fr", "fr"), ("ko", "ko"), ("de", "de")]:
    page = (ROOT / folder / "index.html").read_text(encoding="utf-8") if (ROOT / folder / "index.html").is_file() else ""
    url = f"https://www.kairosaitech.com/{folder}/"
    check(f"{folder}/index.html exists with lang={code}", f'<html lang="{code}"' in page)
    check(f"{folder}/ canonical is self-referencing", f'id="canonicalLink" href="{url}"' in page)
    check(f"{folder}/ is listed in sitemap.xml", f"<loc>{url}</loc>" in sitemap_xml)
    check(f"{folder}/ has no relative asset paths", re.search(r'(?:href|src|poster)="(?![a-z][a-z0-9+.-]*:|/|#)', page) is None)
    check(f"index.html links to {folder}/", f'href="/{folder}/"' in html)
    page_faq = [json.loads(b) for b in re.findall(r'<script type="application/ld\+json">(.*?)</script>', page, re.S) if '"FAQPage"' in b]
    page_ld_q = [q["name"] for q in page_faq[0]["mainEntity"]] if page_faq else []
    page_vis_q = [q.strip() for q in re.findall(r'<summary class="faq-question"[^>]*>(.*?)</summary>', page, re.S)]
    check(f"{folder}/ FAQPage JSON-LD questions match visible FAQ", page_ld_q == page_vis_q and len(page_ld_q) > 0)

sys.exit(1 if failures else 0)
